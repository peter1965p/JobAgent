"""PostgreSQL als optionaler Speicher neben SQLite.

Die App spricht überall SQLite-SQL. Diese Schicht übersetzt es auf dem Weg zum Server, statt jede Abfrage doppelt zu
führen: Platzhalter, INSERT OR IGNORE, lastrowid, PRAGMA, Vektorabstand (sqlite-vec → pgvector) und BLOB-Vektoren.
Jede Person bekommt ein eigenes Schema, so wie sie unter SQLite eine eigene Datei hat. Die Volltextsuche (FTS5)
ersetzt eine Spalte `tsv` mit deutschem Wörterbuch; rag.py fragt sie direkt ab.

Die Verbindung läuft im Autocommit: Die App committet ohnehin nach fast jedem Schreiben, und ein fehlgeschlagener
Befehl soll wie bei SQLite nur sich selbst betreffen, nicht alle folgenden.
"""

from __future__ import annotations

import hashlib
import re
import sqlite3
import struct
import uuid
from pathlib import Path

import psycopg
from psycopg import sql as pgsql
from psycopg.adapt import Dumper, Loader

SCHEMA_PRAEFIX = "js_"


# --- Parameter: Typen bestimmt der Server aus dem Zusammenhang, wie SQLite es tut ----------------------------------

class _OhneTyp(Dumper):
    """Zahlen gehen als „unknown“: Ein Vergleich mit einer TEXT-Spalte klappt dann wie unter SQLite."""

    oid = 0

    def dump(self, obj):
        return str(int(obj) if isinstance(obj, bool) else obj).encode()


class _VektorLoader(Loader):
    """pgvector liefert Text „[0.1,0.2]“. Die App erwartet wie bei sqlite-vec float32-Bytes."""

    def load(self, data):
        text = bytes(data).decode().strip("[]")
        werte = [float(x) for x in text.split(",")] if text else []
        return struct.pack(f"{len(werte)}f", *werte)


def vektor_text(blob: bytes) -> str:
    werte = struct.unpack(f"{len(blob) // 4}f", blob)
    return "[" + ",".join(repr(w) for w in werte) + "]"


def _parameter(werte):
    if werte is None:
        return None
    if isinstance(werte, dict):
        return {k: _wert(v) for k, v in werte.items()}
    return [_wert(v) for v in werte]


def _wert(v):
    if isinstance(v, (bytes, bytearray, memoryview)):
        return vektor_text(bytes(v))
    if isinstance(v, Path):
        return str(v)
    return v


# --- SQL übersetzen ------------------------------------------------------------------------------------------------

_TEXT_ODER_FRAGE = re.compile(r"('(?:[^']|'')*')|(\?)")
_VEC = re.compile(r"vec_distance_cosine\(\s*([\w.]+|\?)\s*,\s*([\w.]+|\?)\s*\)", re.I)
_OR_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO", re.I)
_OR_REPLACE = re.compile(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO", re.I)
_INSERT_TABELLE = re.compile(r"^\s*INSERT\s+(?:OR\s+\w+\s+)?INTO\s+(\w+)", re.I)


def _ausserhalb_text(sql: str, ersetze) -> str:
    """Wendet `ersetze` nur auf Teile außerhalb von String-Literalen an."""
    teile = re.split(r"('(?:[^']|'')*')", sql)
    return "".join(t if i % 2 else ersetze(t) for i, t in enumerate(teile))


def ddl(sql: str) -> str:
    """SQLite-Schema → PostgreSQL. FTS5-Tabelle und ihre Trigger entfallen (Ersatz: Spalte tsv)."""
    sql = re.sub(r"CREATE VIRTUAL TABLE[^;]*;", "", sql, flags=re.I)
    sql = re.sub(r"CREATE TRIGGER.*?\bEND;", "", sql, flags=re.I | re.S)

    def typen(t: str) -> str:
        t = re.sub(r"\bINTEGER PRIMARY KEY(?!\s+CHECK)", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", t, flags=re.I)
        t = re.sub(r"\bINTEGER\b", "BIGINT", t, flags=re.I)
        t = re.sub(r"\bREAL\b", "DOUBLE PRECISION", t, flags=re.I)
        t = re.sub(r"\bBLOB\b", "vector", t, flags=re.I)
        return t

    return _ausserhalb_text(sql, typen)


def uebersetze(sql: str, mit_parametern: bool, benannt: bool = False) -> str:
    kopf = sql.lstrip()[:12].upper()
    if kopf.startswith(("CREATE", "ALTER")):
        sql = ddl(sql)
    ignorieren = bool(_OR_IGNORE.match(sql))
    if ignorieren:
        sql = _OR_IGNORE.sub("INSERT INTO", sql, count=1)
    if _OR_REPLACE.match(sql):
        raise NotImplementedError("INSERT OR REPLACE ist für PostgreSQL nicht übersetzt; bitte ON CONFLICT nutzen.")

    def teil(t: str) -> str:
        t = _VEC.sub(r"(\1 <=> \2)", t)
        t = re.sub(r"\bgroup_concat\(", "string_agg(", t, flags=re.I)
        t = re.sub(r"\bifnull\(", "coalesce(", t, flags=re.I)
        t = re.sub(r"\bLIKE\b", "ILIKE", t, flags=re.I)  # SQLite vergleicht LIKE ohne Groß/Klein
        return t

    sql = _ausserhalb_text(sql, teil)
    if mit_parametern:
        def platzhalter(m):
            return m.group(1) if m.group(1) else "%s"
        # % außerhalb und innerhalb von Literalen verdoppeln, dann ? → %s (nur außerhalb)
        sql = sql.replace("%", "%%")
        sql = _TEXT_ODER_FRAGE.sub(platzhalter, sql)
        if benannt:  # :name → %(name)s, aber nicht ::typ
            sql = _ausserhalb_text(sql, lambda t: re.sub(r"(?<![:\w]):(\w+)", r"%(\1)s", t))
    if ignorieren:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


# --- Zeilen wie sqlite3.Row ----------------------------------------------------------------------------------------

class Zeile(tuple):
    """Zugriff über Index und (ohne Rücksicht auf Groß/Klein) über den Spaltennamen, dazu keys()."""

    __slots__ = ()
    _namen: tuple

    def __new__(cls, namen, werte):
        z = super().__new__(cls, werte)
        return z

    def keys(self):
        return list(self._namen)

    def __getitem__(self, schluessel):
        if isinstance(schluessel, str):
            try:
                return tuple.__getitem__(self, self._index[schluessel.lower()])
            except KeyError:
                raise IndexError(f"Keine Spalte {schluessel!r}") from None
        return tuple.__getitem__(self, schluessel)


def _zeilenfabrik(cursor):
    if cursor.description is None:
        return lambda werte: werte
    namen = tuple(c.name for c in cursor.description)
    index = {}
    for i, n in enumerate(namen):
        index.setdefault(n.lower(), i)
    klasse = type("Zeile", (Zeile,), {"_namen": namen, "_index": index, "__slots__": ()})
    return lambda werte: klasse(namen, werte)


# --- Verbindung und Cursor -----------------------------------------------------------------------------------------

def _fehler(e: psycopg.Error) -> sqlite3.Error:
    """Aufrufer kennen die Ausnahmen von sqlite3. Die Ursache hängt mit dran."""
    if isinstance(e, psycopg.IntegrityError):
        neu = sqlite3.IntegrityError(str(e).strip())
    elif isinstance(e, psycopg.OperationalError):
        neu = sqlite3.OperationalError(str(e).strip())
    else:
        neu = sqlite3.OperationalError(str(e).strip())
    neu.__cause__ = e
    return neu


class Cursor:
    def __init__(self, verbindung: "Verbindung"):
        self._v = verbindung
        self._c = verbindung.roh.cursor(row_factory=_zeilenfabrik)
        self.lastrowid = None
        self._rueckgabe_nur_id = False

    @property
    def rowcount(self):
        return self._c.rowcount

    @property
    def description(self):
        if self._rueckgabe_nur_id or self._c.description is None:
            return None
        return [(c.name, None, None, None, None, None, None) for c in self._c.description]

    def execute(self, sql: str, parameter=()):
        parameter = _parameter(parameter) if parameter else None
        text = uebersetze(sql, parameter is not None, isinstance(parameter, dict))
        tabelle = _INSERT_TABELLE.match(sql)
        self._rueckgabe_nur_id = bool(tabelle and tabelle.group(1).lower() in self._v.tabellen_mit_id()
                                      and not re.search(r"\bRETURNING\b", text, re.I))
        if self._rueckgabe_nur_id:
            text = text.rstrip().rstrip(";") + " RETURNING id"
        try:
            self._c.execute(text, parameter)
        except psycopg.Error as e:
            raise _fehler(e) from e
        self.lastrowid = None
        if self._rueckgabe_nur_id:
            ids = self._c.fetchall()
            self.lastrowid = ids[-1][0] if ids else None
        if kopf_ist_ddl(sql):
            self._v.vergiss_tabellen()
        return self

    def executemany(self, sql: str, folge):
        folge = [_parameter(p) for p in folge]
        try:
            self._c.executemany(uebersetze(sql, True, bool(folge) and isinstance(folge[0], dict)), folge)
        except psycopg.Error as e:
            raise _fehler(e) from e
        return self

    def fetchone(self):
        if self._rueckgabe_nur_id or self._c.description is None:
            return None
        return self._c.fetchone()

    def fetchall(self):
        if self._rueckgabe_nur_id or self._c.description is None:
            return []
        return self._c.fetchall()

    def fetchmany(self, n=1):
        if self._rueckgabe_nur_id or self._c.description is None:
            return []
        return self._c.fetchmany(n)

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        self._c.close()


def kopf_ist_ddl(sql: str) -> bool:
    return sql.lstrip()[:6].upper() in ("CREATE", "ALTER ", "DROP T")


class Verbindung:
    """Verhält sich für die App wie eine sqlite3.Connection."""

    def __init__(self, roh: psycopg.Connection, schema: str, temporaer: bool = False):
        self.roh = roh
        self.schema = schema
        self.temporaer = temporaer
        self._mit_id: set[str] | None = None
        self.row_factory = None  # nur zur Verträglichkeit

    # sqlite3-Schnittstelle
    def cursor(self):
        return Cursor(self)

    def execute(self, sql: str, parameter=()):
        if re.match(r"\s*PRAGMA\b", sql, re.I):
            return _Pragma(self, sql)
        return Cursor(self).execute(sql, parameter)

    def executemany(self, sql: str, folge):
        return Cursor(self).executemany(sql, folge)

    def executescript(self, skript: str):
        text = ddl(skript)
        if text.strip():
            try:
                self.roh.execute(text)
            except psycopg.Error as e:
                raise _fehler(e) from e
        self.vergiss_tabellen()
        return self

    def commit(self):
        pass  # Autocommit

    def rollback(self):
        pass

    def close(self):
        if self.roh.closed:
            return
        if self.temporaer:
            try:
                self.roh.execute(pgsql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(pgsql.Identifier(self.schema)))
            except psycopg.Error:
                pass
        self.roh.close()

    def __enter__(self):
        return self

    def __exit__(self, *_):
        return False

    @property
    def in_transaction(self):
        return False

    # intern
    def tabellen_mit_id(self) -> set[str]:
        if self._mit_id is None:
            self._mit_id = {z[0] for z in self.roh.execute(
                "SELECT table_name FROM information_schema.columns WHERE table_schema = %s AND column_name = 'id'",
                (self.schema,))}
        return self._mit_id

    def vergiss_tabellen(self):
        self._mit_id = None

    def spalten(self, tabelle: str) -> list[str]:
        return [z[0] for z in self.roh.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_schema = %s AND table_name = %s "
            "ORDER BY ordinal_position", (self.schema, tabelle))]


class _Pragma:
    """Die zwei PRAGMAs, die die App nutzt: table_info liefert Spalten, alles andere ist unter Postgres egal."""

    def __init__(self, v: Verbindung, sql: str):
        m = re.match(r"\s*PRAGMA\s+table_info\((\w+)\)", sql, re.I)
        klasse = type("Zeile", (Zeile,), {"_namen": ("cid", "name"), "_index": {"cid": 0, "name": 1}, "__slots__": ()})
        self._zeilen = [klasse(None, (i, n)) for i, n in enumerate(v.spalten(m.group(1)))] if m else []

    def __iter__(self):
        return iter(self._zeilen)

    def fetchall(self):
        return list(self._zeilen)

    def fetchone(self):
        return self._zeilen[0] if self._zeilen else None


# --- Verbinden ------------------------------------------------------------------------------------------------------

def schema_fuer(pfad: Path | str, daten: Path) -> str:
    """Der SQLite-Pfad bestimmt das Schema. So bleibt die Zuordnung „eine Person, ein Speicher“ gleich."""
    p = Path(pfad)
    try:
        schluessel = p.resolve().relative_to(daten.resolve()).as_posix()
    except ValueError:
        schluessel = str(p.resolve())
    return SCHEMA_PRAEFIX + hashlib.sha256(schluessel.encode()).hexdigest()[:16]


def roh_verbinden(server: dict) -> psycopg.Connection:
    passwort = server.get("passwort")
    if passwort is None:
        import keyring
        passwort = keyring.get_password("jobsuche", schluessel(server)) or ""
    roh = psycopg.connect(
        host=server["host"], port=int(server.get("port") or 5432), dbname=server["datenbank"],
        user=server["benutzer"], password=passwort, sslmode=server.get("sslmode", "require"),
        connect_timeout=int(server.get("timeout", 8)), autocommit=True,
        application_name="jobagent",
    )
    for typ in (int, float, bool):
        roh.adapters.register_dumper(typ, _OhneTyp)
    zeile = roh.execute("SELECT oid FROM pg_type WHERE typname = 'vector'").fetchone()
    if zeile is None:
        roh.close()
        raise sqlite3.OperationalError(
            "Auf dem Server fehlt die Erweiterung pgvector (CREATE EXTENSION vector; als Administrator).")
    roh.adapters.register_loader(zeile[0], _VektorLoader)
    return roh


def schluessel(server: dict) -> str:
    return f"postgres:{server['benutzer']}@{server['host']}"


def verbinden(server: dict, schema: str | None, schema_sql: str, nachher=None, rolle: str | None = None) -> Verbindung:
    """Verbindet, legt Schema und Tabellen an. `schema=None` = temporäres Schema (Tests).

    Mit `rolle` (Mandant) wechselt die Verbindung vorher per SET ROLE in die Datenbankrolle des Mandanten. Die besitzt
    nur ihr eigenes Schema; auf andere Schemata und die zentralen Konten hat sie keine Rechte."""
    temporaer = schema is None
    schema = schema or SCHEMA_PRAEFIX + "tmp_" + uuid.uuid4().hex[:12]
    try:
        roh = roh_verbinden(server)
        if rolle:
            roh.execute(pgsql.SQL("SET ROLE {}").format(pgsql.Identifier(rolle)))
        else:
            roh.execute(pgsql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(pgsql.Identifier(schema)))
        roh.execute(pgsql.SQL("SET search_path TO {}, public").format(pgsql.Identifier(schema)))
    except psycopg.Error as e:
        raise _fehler(e) from e
    v = Verbindung(roh, schema, temporaer)
    kennung = (server["host"], int(server.get("port") or 5432), server["datenbank"], schema, rolle or "")
    if kennung not in _eingerichtet:  # Jede Hintergrundaufgabe verbindet neu: das Schema nur einmal je Prozess prüfen
        roh.execute("SET client_min_messages TO warning")
        v.executescript(schema_sql)
        v.executescript(
            "ALTER TABLE chunks ADD COLUMN IF NOT EXISTS tsv tsvector "
            "GENERATED ALWAYS AS (to_tsvector('german', text)) STORED;"
            "CREATE INDEX IF NOT EXISTS chunks_tsv ON chunks USING gin (tsv);"
        )
        if nachher:
            nachher(v)
        if not temporaer:
            _eingerichtet.add(kennung)
    return v


_eingerichtet: set[tuple] = set()


def schema_existiert(server: dict, schema: str) -> bool:
    with roh_verbinden(server) as roh:
        return roh.execute("SELECT 1 FROM information_schema.schemata WHERE schema_name = %s", (schema,)).fetchone() is not None


def pruefe(server: dict) -> str:
    """Für den Knopf „Verbindung testen“: Version und pgvector."""
    try:
        with roh_verbinden(server) as roh:
            version = roh.execute("SHOW server_version").fetchone()[0]
            ssl = roh.execute("SELECT ssl FROM pg_stat_ssl WHERE pid = pg_backend_pid()").fetchone()
            vec = roh.execute("SELECT extversion FROM pg_extension WHERE extname = 'vector'").fetchone()
    except (psycopg.Error, sqlite3.Error) as e:
        return f"Keine Verbindung: {str(e).strip().splitlines()[0]}"
    return (f"Verbunden: PostgreSQL {version}, pgvector {vec[0] if vec else '?'}, "
            f"{'verschlüsselt (TLS)' if ssl and ssl[0] else 'unverschlüsselt'}.")


# --- Übernahme aus SQLite --------------------------------------------------------------------------------------------

def _reihenfolge(quelle: sqlite3.Connection, tabellen: list[str]) -> list[str]:
    """Eltern vor Kindern, damit Fremdschlüssel beim Einfügen schon ein Ziel haben."""
    abhaengig = {t: {z[2] for z in quelle.execute(f"PRAGMA foreign_key_list({t})") if z[2] in tabellen and z[2] != t}
                 for t in tabellen}
    fertig: list[str] = []
    while abhaengig:
        frei = sorted(t for t, d in abhaengig.items() if d <= set(fertig))
        if not frei:  # Kreis: Rest in beliebiger Folge
            frei = sorted(abhaengig)
        for t in frei:
            fertig.append(t)
            abhaengig.pop(t)
    return fertig


def uebernimm(quelle_pfad: Path, ziel: Verbindung, ersetzen: bool = False, melde=lambda _: None) -> dict[str, tuple[int, int, int]]:
    """Kopiert alle Tabellen einer SQLite-Datei in das Schema von `ziel`. Die Datei bleibt unverändert.

    Ergebnis je Tabelle: (Zeilen in SQLite, Zeilen in Postgres danach, übersprungene Zeilen).
    """
    quelle = sqlite3.connect(f"file:{Path(quelle_pfad)}?mode=ro", uri=True)
    quelle.row_factory = sqlite3.Row
    try:
        tabellen = {z["name"]: z["sql"] for z in quelle.execute(
            "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' "
            "AND name NOT LIKE 'chunks_fts%'")}
        vorhanden = set(ziel.roh.execute(
            "SELECT table_name FROM information_schema.tables WHERE table_schema = %s", (ziel.schema,)).fetchall())
        vorhanden = {z[0] for z in vorhanden}
        for name, ddl_text in tabellen.items():
            if name not in vorhanden:
                ziel.executescript(ddl_text.rstrip(";") + ";")
        reihenfolge = _reihenfolge(quelle, list(tabellen))
        belegt = [t for t in reihenfolge if ziel.roh.execute(
            pgsql.SQL("SELECT 1 FROM {} LIMIT 1").format(pgsql.Identifier(t))).fetchone()]
        if belegt and not ersetzen:
            raise ValueError("Im Ziel liegen schon Daten (" + ", ".join(belegt) + "). Übernahme mit „ersetzen“ wiederholen.")
        if belegt:
            ziel.roh.execute(pgsql.SQL("TRUNCATE {} CASCADE").format(
                pgsql.SQL(", ").join(pgsql.Identifier(t) for t in reihenfolge)))
        ergebnis: dict[str, tuple[int, int, int]] = {}
        for t in reihenfolge:
            spalten_quelle = [z["name"] for z in quelle.execute(f"PRAGMA table_info({t})")]
            spalten_ziel = set(ziel.spalten(t))
            spalten = [s for s in spalten_quelle if s in spalten_ziel]
            zeilen = [tuple(z) for z in quelle.execute(
                f"SELECT {', '.join(chr(34) + s + chr(34) for s in spalten)} FROM \"{t}\"")]
            einfuegen = pgsql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                pgsql.Identifier(t), pgsql.SQL(", ").join(pgsql.Identifier(s) for s in spalten),
                pgsql.SQL(", ").join(pgsql.Placeholder() * len(spalten)))
            werte = [_parameter(z) for z in zeilen]
            uebersprungen = 0
            try:
                with ziel.roh.transaction():
                    with ziel.roh.cursor() as c:
                        c.executemany(einfuegen, werte)
            except psycopg.Error:
                # Einzeln nachholen: kaputte Altzeilen (z. B. verwaiste Fremdschlüssel) überspringen, Rest übernehmen
                for w in werte:
                    try:
                        ziel.roh.execute(einfuegen, w)
                    except psycopg.Error:
                        uebersprungen += 1
            if "id" in spalten:
                ziel.roh.execute(pgsql.SQL(
                    "SELECT setval(pg_get_serial_sequence({tab}, 'id'), coalesce(max(id), 1), max(id) IS NOT NULL) FROM {t}"
                ).format(tab=pgsql.Literal(f"{ziel.schema}.{t}"), t=pgsql.Identifier(t)))
            danach = ziel.roh.execute(pgsql.SQL("SELECT count(*) FROM {}").format(pgsql.Identifier(t))).fetchone()[0]
            ergebnis[t] = (len(zeilen), danach, uebersprungen)
            melde(f"{t}: {danach} von {len(zeilen)} Zeilen")
        ziel.vergiss_tabellen()
        return ergebnis
    finally:
        quelle.close()


def sqlite_dateien(daten: Path) -> list[Path]:
    """Alle Personen-Datenbanken unter `daten/` (ohne Demo)."""
    kandidaten = [daten / "jobsuche.db", *sorted((daten / "personen").glob("*/jobsuche.db"))]
    return [p for p in kandidaten if p.exists()]


def uebernimm_alle(ersetzen: bool = False, melde=print) -> dict[str, dict[str, tuple[int, int, int]]]:
    """Kopiert jede lokale Personen-Datenbank in ihr Schema auf dem eingestellten Server."""
    from . import config, db
    if not db.server():
        raise ValueError("Es ist kein PostgreSQL-Server eingestellt.")
    ergebnis = {}
    for datei in sqlite_dateien(config.DATEN):
        melde(f"– {datei.relative_to(config.DATEN)}")
        ziel = db.verbinden(datei)
        try:
            ergebnis[str(datei)] = uebernimm(datei, ziel, ersetzen=ersetzen, melde=lambda t: melde("  " + t))
        finally:
            ziel.close()
    return ergebnis


def _haupt(argv: list[str] | None = None) -> int:
    import argparse

    from . import db
    teil = argparse.ArgumentParser(prog="python -m jobsuche.pg", description="Job Agent und PostgreSQL")
    befehle = teil.add_subparsers(dest="befehl", required=True)
    befehle.add_parser("pruefen", help="Verbindung zum eingestellten Server testen")
    u = befehle.add_parser("uebernehmen", help="lokale SQLite-Daten auf den Server kopieren (Dateien bleiben)")
    u.add_argument("--ersetzen", action="store_true", help="vorhandene Daten auf dem Server überschreiben")
    args = teil.parse_args(argv)
    s = db.server()
    if not s:
        print("Kein Server eingestellt (System → Daten in der App, oder daten/datenbank.json).")
        return 2
    if args.befehl == "pruefen":
        print(pruefe(s))
        return 0
    fehler = 0
    for datei, tabellen in uebernimm_alle(args.ersetzen).items():
        for t, (vorher, nachher, weg) in tabellen.items():
            if vorher != nachher:
                fehler += 1
                print(f"ABWEICHUNG {datei} {t}: SQLite {vorher}, Postgres {nachher}, übersprungen {weg}")
    print("Fertig, alle Zeilen übernommen." if not fehler else f"Fertig mit {fehler} Abweichungen.")
    return 1 if fehler else 0


if __name__ == "__main__":
    raise SystemExit(_haupt())
