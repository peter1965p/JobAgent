"""Konten und Mandanten in PostgreSQL: zentrale Tabellen im Schema `js_zentral`, Daten je Mandant im eigenen Schema.

Trennung (warum so):
- Jeder Mandant hat eine eigene Datenbankrolle (NOLOGIN) und ein eigenes Schema, das dieser Rolle gehört. Die App
  verbindet sich mit einem Anmelde-Benutzer und wechselt per SET ROLE in die Mandantenrolle. Ab dann prüft der Server
  jeden Zugriff: Ein fremdes Schema ist „permission denied“, auch wenn ein Fehler im Code den search_path oder einen
  Tabellennamen falsch setzt. search_path allein wäre keine Grenze, RLS auf allen Fachtabellen wäre ein zweites,
  leicht zu vergessendes Regelwerk für ~15 Tabellen. Rolle + Schema trennt vollständig und mit einer Regel.
- Die zentralen Tabellen (Konten, Sitzungen, Einladungen …) sieht keine Mandantenrolle. Nur `mandanten` ist für
  Mandantenrollen lesbar, und dort sorgt Row-Level-Security dafür, dass jede Rolle nur ihre eigene Zeile sieht
  (z. B. ob Claude freigegeben ist). Ändern dürfen sie nichts.
- Der Webdienst meldet sich als eigener Benutzer an (`jobagent_web`, in `betreiber` eingetragen). Er ist Mitglied
  jeder Mandantenrolle nur mit SET, ohne INHERIT: Ohne SET ROLE hat er keinerlei Rechte an Mandantendaten.
- Neue Mandanten legt die Funktion `js_zentral.mandant_anlegen` an (SECURITY DEFINER, gehört dem Besitzer der
  Datenbank, der CREATEROLE hat). Der Webdienst braucht dafür selbst kein CREATEROLE.

Passwörter der Konten: argon2id (argon2-cffi). Das Mailpasswort bleibt getrennt davon und dient nur dem Versand.
"""

from __future__ import annotations

import hashlib
import secrets
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path

import psycopg
from argon2 import PasswordHasher
from argon2.exceptions import InvalidHashError, VerificationError, VerifyMismatchError
from psycopg import sql as pgsql

from . import db, pg

ZENTRAL = "js_zentral"
GRUPPE = "js_mandanten"  # alle Mandantenrollen sind Mitglied, für den Lesezugriff auf die eigene Mandantenzeile
WEB_ROLLE = "jobagent_web"
MIN_PASSWORT = 12
MAX_FEHLVERSUCHE = 5
SPERRE = timedelta(minutes=15)
EINLADUNG_GUELTIG = timedelta(days=7)

_hasher = PasswordHasher()  # argon2id, Standardparameter von argon2-cffi (RFC 9106, „low memory“)


class KontoFehler(Exception):
    """Meldung für den Menschen. Bei der Anmeldung absichtlich ohne Unterschied zwischen „gibt es nicht“ und „falsch“."""


@dataclass(frozen=True)
class Konto:
    id: int
    email: str
    name: str
    admin: bool


@dataclass(frozen=True)
class MandantInfo:
    id: int
    name: str
    schema: str
    rolle: str
    claude_erlaubt: bool
    mitgliedsrolle: str = "inhaber"


# --- Einrichtung -----------------------------------------------------------------------------------------------------

DDL = f"""
CREATE SCHEMA IF NOT EXISTS {ZENTRAL};
CREATE TABLE IF NOT EXISTS {ZENTRAL}.konten (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE CHECK (email = lower(email) AND position('@' in email) > 1),
    name TEXT NOT NULL DEFAULT '',
    pw_hash TEXT NOT NULL,
    admin BOOLEAN NOT NULL DEFAULT false,
    aktiv BOOLEAN NOT NULL DEFAULT true,
    fehlversuche INTEGER NOT NULL DEFAULT 0,
    gesperrt_bis TIMESTAMPTZ,
    erstellt TIMESTAMPTZ NOT NULL DEFAULT now(),
    letzte_anmeldung TIMESTAMPTZ,
    zuletzt_mandant BIGINT
);
CREATE TABLE IF NOT EXISTS {ZENTRAL}.mandanten (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    schema TEXT NOT NULL UNIQUE,
    rolle TEXT NOT NULL UNIQUE,
    claude_erlaubt BOOLEAN NOT NULL DEFAULT false,
    nachtlauf BOOLEAN NOT NULL DEFAULT false,
    nachtlauf_uhrzeit TEXT NOT NULL DEFAULT '01:00',
    nachtlauf_zuletzt DATE,
    erstellt TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS {ZENTRAL}.mitglieder (
    konto_id BIGINT NOT NULL REFERENCES {ZENTRAL}.konten(id) ON DELETE CASCADE,
    mandant_id BIGINT NOT NULL REFERENCES {ZENTRAL}.mandanten(id) ON DELETE CASCADE,
    rolle TEXT NOT NULL DEFAULT 'inhaber' CHECK (rolle IN ('inhaber', 'mitglied')),
    PRIMARY KEY (konto_id, mandant_id)
);
CREATE TABLE IF NOT EXISTS {ZENTRAL}.einladungen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash TEXT NOT NULL UNIQUE,
    notiz TEXT NOT NULL DEFAULT '',
    mandant_id BIGINT REFERENCES {ZENTRAL}.mandanten(id) ON DELETE CASCADE,
    erstellt_von BIGINT REFERENCES {ZENTRAL}.konten(id) ON DELETE SET NULL,
    erstellt TIMESTAMPTZ NOT NULL DEFAULT now(),
    gueltig_bis TIMESTAMPTZ NOT NULL,
    benutzt_von BIGINT REFERENCES {ZENTRAL}.konten(id) ON DELETE SET NULL,
    benutzt_am TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS {ZENTRAL}.sitzungen (
    token_hash TEXT PRIMARY KEY,
    konto_id BIGINT NOT NULL REFERENCES {ZENTRAL}.konten(id) ON DELETE CASCADE,
    mandant_id BIGINT REFERENCES {ZENTRAL}.mandanten(id) ON DELETE SET NULL,
    csrf TEXT NOT NULL,
    erstellt TIMESTAMPTZ NOT NULL DEFAULT now(),
    ablauf TIMESTAMPTZ NOT NULL,
    ip TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS sitzungen_konto ON {ZENTRAL}.sitzungen(konto_id);
CREATE TABLE IF NOT EXISTS {ZENTRAL}.protokoll (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zeit TIMESTAMPTZ NOT NULL DEFAULT now(),
    konto_id BIGINT,
    aktion TEXT NOT NULL,
    ip TEXT NOT NULL DEFAULT '',
    detail TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS {ZENTRAL}.betreiber (rolle TEXT PRIMARY KEY);

-- Die Rolle kommt als Argument: In einer SECURITY-DEFINER-Funktion wäre current_user der Besitzer, nicht der Aufrufer.
DROP POLICY IF EXISTS sicht ON {ZENTRAL}.mandanten;
DROP POLICY IF EXISTS betrieb ON {ZENTRAL}.mandanten;
DROP FUNCTION IF EXISTS {ZENTRAL}.ist_betreiber();
CREATE OR REPLACE FUNCTION {ZENTRAL}.ist_betreiber(r name) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = {ZENTRAL}, pg_temp
AS $$ SELECT EXISTS (SELECT 1 FROM {ZENTRAL}.betreiber WHERE rolle = r) $$;

ALTER TABLE {ZENTRAL}.mandanten ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS sicht ON {ZENTRAL}.mandanten;
CREATE POLICY sicht ON {ZENTRAL}.mandanten FOR SELECT USING (rolle = current_user OR {ZENTRAL}.ist_betreiber(current_user));
DROP POLICY IF EXISTS betrieb ON {ZENTRAL}.mandanten;
CREATE POLICY betrieb ON {ZENTRAL}.mandanten FOR ALL USING ({ZENTRAL}.ist_betreiber(current_user)) WITH CHECK ({ZENTRAL}.ist_betreiber(current_user));

CREATE OR REPLACE FUNCTION {ZENTRAL}.mandant_anlegen(p_name text) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = {ZENTRAL}, pg_temp
AS $$
DECLARE
    r text := 'js_m' || substr(md5(gen_random_uuid()::text), 1, 14);
    b record;
    neu bigint;
BEGIN
    IF NOT (ist_betreiber(session_user) OR current_user = session_user) THEN
        RAISE EXCEPTION 'nur für Betreiber';
    END IF;
    EXECUTE format('CREATE ROLE %I NOLOGIN', r);
    EXECUTE format('GRANT %I TO %I WITH INHERIT FALSE, SET TRUE', r, current_user);
    FOR b IN SELECT bt.rolle FROM betreiber bt JOIN pg_roles pr ON pr.rolname = bt.rolle WHERE bt.rolle <> current_user LOOP
        EXECUTE format('GRANT %I TO %I WITH INHERIT FALSE, SET TRUE', r, b.rolle);
    END LOOP;
    EXECUTE format('GRANT {GRUPPE} TO %I', r);
    EXECUTE format('CREATE SCHEMA %I AUTHORIZATION %I', r, r);
    INSERT INTO mandanten (name, schema, rolle) VALUES (p_name, r, r) RETURNING id INTO neu;
    RETURN neu;
END
$$;
REVOKE ALL ON FUNCTION {ZENTRAL}.mandant_anlegen(text) FROM PUBLIC;
"""


def _gruppe_anlegen(roh: psycopg.Connection) -> None:
    if not roh.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (GRUPPE,)).fetchone():
        roh.execute(pgsql.SQL("CREATE ROLE {} NOLOGIN").format(pgsql.Identifier(GRUPPE)))


def einrichten(roh: psycopg.Connection, web_rolle: str | None = WEB_ROLLE) -> None:
    """Legt das zentrale Schema an oder bringt es auf Stand. Läuft als Besitzer der Datenbank (mit CREATEROLE).
    `web_rolle` bekommt die Rechte des Webdienstes, wenn es sie gibt."""
    _gruppe_anlegen(roh)
    roh.execute("SET client_min_messages TO warning")
    with roh.transaction():
        roh.execute(DDL)
        roh.execute(pgsql.SQL("GRANT USAGE ON SCHEMA {} TO {}").format(pgsql.Identifier(ZENTRAL), pgsql.Identifier(GRUPPE)))
        roh.execute(pgsql.SQL("GRANT SELECT ON {}.mandanten TO {}").format(pgsql.Identifier(ZENTRAL), pgsql.Identifier(GRUPPE)))
        if web_rolle and roh.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (web_rolle,)).fetchone():
            w = pgsql.Identifier(web_rolle)
            z = pgsql.Identifier(ZENTRAL)
            roh.execute(pgsql.SQL("GRANT USAGE ON SCHEMA {} TO {}").format(z, w))
            roh.execute(pgsql.SQL("GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA {} TO {}").format(z, w))
            roh.execute(pgsql.SQL("REVOKE INSERT, UPDATE, DELETE ON {}.betreiber FROM {}").format(z, w))
            roh.execute(pgsql.SQL("GRANT USAGE ON ALL SEQUENCES IN SCHEMA {} TO {}").format(z, w))
            roh.execute(pgsql.SQL("GRANT EXECUTE ON FUNCTION {}.mandant_anlegen(text) TO {}").format(z, w))
            roh.execute(f"INSERT INTO {ZENTRAL}.betreiber (rolle) VALUES (%s) ON CONFLICT DO NOTHING", (web_rolle,))
            # Bestehenden Mandanten nachträglich den Webdienst als Mitglied geben (nur SET, keine geerbten Rechte)
            for (rolle,) in roh.execute(f"SELECT rolle FROM {ZENTRAL}.mandanten").fetchall():
                roh.execute(pgsql.SQL("GRANT {} TO {} WITH INHERIT FALSE, SET TRUE").format(pgsql.Identifier(rolle), w))


def ist_eingerichtet(roh: psycopg.Connection) -> bool:
    return roh.execute("SELECT 1 FROM information_schema.tables WHERE table_schema = %s AND table_name = 'konten'",
                       (ZENTRAL,)).fetchone() is not None


def zentral_verbinden(server: dict | None = None) -> psycopg.Connection:
    server = server or db.server()
    if not server:
        raise KontoFehler("Konten gibt es nur mit PostgreSQL. Es ist kein Server eingestellt.")
    return pg.roh_verbinden(server)


# --- Passwörter ------------------------------------------------------------------------------------------------------

def pruefe_passwortregel(passwort: str, email: str = "") -> None:
    if len(passwort) < MIN_PASSWORT:
        raise KontoFehler(f"Das Passwort braucht mindestens {MIN_PASSWORT} Zeichen.")
    if len(passwort) > 256:
        raise KontoFehler("Das Passwort ist zu lang (höchstens 256 Zeichen).")
    if email and passwort.strip().lower() == email.strip().lower():
        raise KontoFehler("Das Passwort darf nicht die Mailadresse sein.")


def hash_passwort(passwort: str) -> str:
    return _hasher.hash(passwort)


def passwort_passt(gespeichert: str, passwort: str) -> bool:
    try:
        return _hasher.verify(gespeichert, passwort)
    except (VerifyMismatchError, VerificationError, InvalidHashError):
        return False


_ATTRAPPE = _hasher.hash(secrets.token_hex(16))  # gleiche Laufzeit, auch wenn es das Konto nicht gibt


def _adresse(email: str) -> str:
    return email.strip().lower()


# --- Konten ----------------------------------------------------------------------------------------------------------

def protokolliere(roh, konto_id: int | None, aktion: str, ip: str = "", detail: str = "") -> None:
    roh.execute(f"INSERT INTO {ZENTRAL}.protokoll (konto_id, aktion, ip, detail) VALUES (%s, %s, %s, %s)",
                (konto_id, aktion, ip[:64], detail[:500]))


def _konto(zeile) -> Konto:
    return Konto(zeile[0], zeile[1], zeile[2], bool(zeile[3]))


def konto_anlegen(roh, email: str, passwort: str, name: str = "", admin: bool = False) -> Konto:
    email = _adresse(email)
    if "@" not in email or len(email) > 254:
        raise KontoFehler("Die Mailadresse ist ungültig.")
    pruefe_passwortregel(passwort, email)
    try:
        zeile = roh.execute(
            f"INSERT INTO {ZENTRAL}.konten (email, name, pw_hash, admin) VALUES (%s, %s, %s, %s) "
            "RETURNING id, email, name, admin", (email, name.strip()[:120], hash_passwort(passwort), admin)).fetchone()
    except psycopg.errors.UniqueViolation:
        raise KontoFehler("Für diese Adresse gibt es schon ein Konto.") from None
    protokolliere(roh, zeile[0], "Konto angelegt")
    return _konto(zeile)


def anmelden(roh, email: str, passwort: str, ip: str = "", jetzt: datetime | None = None) -> Konto:
    """Prüft Adresse und Passwort. Nach MAX_FEHLVERSUCHE Fehlern ist das Konto SPERRE lang gesperrt."""
    jetzt = jetzt or datetime.now(timezone.utc)
    zeile = roh.execute(
        f"SELECT id, email, name, admin, pw_hash, aktiv, fehlversuche, gesperrt_bis FROM {ZENTRAL}.konten WHERE email = %s",
        (_adresse(email),)).fetchone()
    falsch = KontoFehler("Adresse oder Passwort stimmt nicht.")
    if zeile is None:
        passwort_passt(_ATTRAPPE, passwort)
        protokolliere(roh, None, "Anmeldung fehlgeschlagen", ip, "unbekannte Adresse")
        raise falsch
    if zeile[7] is not None and zeile[7] > jetzt:
        passwort_passt(_ATTRAPPE, passwort)
        protokolliere(roh, zeile[0], "Anmeldung während Sperre", ip)
        raise KontoFehler("Zu viele Fehlversuche. Das Konto ist für einige Minuten gesperrt.")
    if not passwort_passt(zeile[4], passwort):
        fehl = zeile[6] + 1
        sperre = jetzt + SPERRE if fehl >= MAX_FEHLVERSUCHE else None
        roh.execute(f"UPDATE {ZENTRAL}.konten SET fehlversuche = %s, gesperrt_bis = %s WHERE id = %s",
                    (0 if sperre else fehl, sperre, zeile[0]))
        protokolliere(roh, zeile[0], "Anmeldung fehlgeschlagen", ip, "gesperrt" if sperre else "")
        raise falsch
    if not zeile[5]:
        protokolliere(roh, zeile[0], "Anmeldung eines deaktivierten Kontos", ip)
        raise falsch
    if _hasher.check_needs_rehash(zeile[4]):
        roh.execute(f"UPDATE {ZENTRAL}.konten SET pw_hash = %s WHERE id = %s", (hash_passwort(passwort), zeile[0]))
    roh.execute(f"UPDATE {ZENTRAL}.konten SET fehlversuche = 0, gesperrt_bis = NULL, letzte_anmeldung = now() WHERE id = %s",
                (zeile[0],))
    protokolliere(roh, zeile[0], "Anmeldung", ip)
    return _konto(zeile)


def konto(roh, konto_id: int) -> Konto | None:
    zeile = roh.execute(f"SELECT id, email, name, admin FROM {ZENTRAL}.konten WHERE id = %s AND aktiv", (konto_id,)).fetchone()
    return _konto(zeile) if zeile else None


def aendere_passwort(roh, konto_id: int, alt: str, neu: str) -> None:
    zeile = roh.execute(f"SELECT email, pw_hash FROM {ZENTRAL}.konten WHERE id = %s", (konto_id,)).fetchone()
    if not zeile or not passwort_passt(zeile[1], alt):
        raise KontoFehler("Das bisherige Passwort stimmt nicht.")
    pruefe_passwortregel(neu, zeile[0])
    roh.execute(f"UPDATE {ZENTRAL}.konten SET pw_hash = %s WHERE id = %s", (hash_passwort(neu), konto_id))
    protokolliere(roh, konto_id, "Passwort geändert")


def setze_passwort(roh, konto_id: int, neu: str) -> None:
    """Betreiber: Passwort neu setzen (z. B. bei der Übernahme), ohne das alte zu kennen."""
    zeile = roh.execute(f"SELECT email FROM {ZENTRAL}.konten WHERE id = %s", (konto_id,)).fetchone()
    if not zeile:
        raise KontoFehler("Konto unbekannt.")
    pruefe_passwortregel(neu, zeile[0])
    roh.execute(f"UPDATE {ZENTRAL}.konten SET pw_hash = %s, fehlversuche = 0, gesperrt_bis = NULL WHERE id = %s",
                (hash_passwort(neu), konto_id))
    protokolliere(roh, konto_id, "Passwort gesetzt (Betreiber)")


def konten(roh) -> list[dict]:
    spalten = ("id", "email", "name", "admin", "aktiv", "gesperrt_bis", "letzte_anmeldung", "erstellt")
    return [dict(zip(spalten, z)) for z in roh.execute(
        f"SELECT {', '.join(spalten)} FROM {ZENTRAL}.konten ORDER BY id").fetchall()]


def setze_aktiv(roh, konto_id: int, aktiv: bool) -> None:
    roh.execute(f"UPDATE {ZENTRAL}.konten SET aktiv = %s WHERE id = %s", (aktiv, konto_id))
    if not aktiv:
        roh.execute(f"DELETE FROM {ZENTRAL}.sitzungen WHERE konto_id = %s", (konto_id,))


# --- Mandanten -------------------------------------------------------------------------------------------------------

def mandant_anlegen(roh, name: str, inhaber_id: int | None = None) -> int:
    mid = roh.execute(f"SELECT {ZENTRAL}.mandant_anlegen(%s)", (name.strip()[:120] or "Mandant",)).fetchone()[0]
    if inhaber_id is not None:
        mitglied_machen(roh, inhaber_id, mid, "inhaber")
    return mid


def mitglied_machen(roh, konto_id: int, mandant_id: int, rolle: str = "mitglied") -> None:
    roh.execute(f"INSERT INTO {ZENTRAL}.mitglieder (konto_id, mandant_id, rolle) VALUES (%s, %s, %s) "
                "ON CONFLICT (konto_id, mandant_id) DO UPDATE SET rolle = excluded.rolle", (konto_id, mandant_id, rolle))


def mandanten_von(roh, konto_id: int) -> list[MandantInfo]:
    return [MandantInfo(*z) for z in roh.execute(
        f"SELECT m.id, m.name, m.schema, m.rolle, m.claude_erlaubt, mg.rolle FROM {ZENTRAL}.mandanten m "
        f"JOIN {ZENTRAL}.mitglieder mg ON mg.mandant_id = m.id WHERE mg.konto_id = %s ORDER BY m.id", (konto_id,)).fetchall()]


def mandant_fuer(roh, konto_id: int, mandant_id: int | None) -> MandantInfo:
    """Der gewünschte Mandant, wenn das Konto Mitglied ist, sonst der zuletzt genutzte bzw. erste."""
    alle = mandanten_von(roh, konto_id)
    if not alle:
        raise KontoFehler("Dieses Konto gehört zu keinem Mandanten.")
    if mandant_id is not None:
        gewaehlt = next((m for m in alle if m.id == mandant_id), None)
        if gewaehlt is None:
            raise KontoFehler("Kein Zugriff auf diesen Mandanten.")
    else:
        zuletzt = roh.execute(f"SELECT zuletzt_mandant FROM {ZENTRAL}.konten WHERE id = %s", (konto_id,)).fetchone()
        gewaehlt = next((m for m in alle if zuletzt and m.id == zuletzt[0]), alle[0])
    roh.execute(f"UPDATE {ZENTRAL}.konten SET zuletzt_mandant = %s WHERE id = %s", (gewaehlt.id, konto_id))
    return gewaehlt


def alle_mandanten(roh) -> list[dict]:
    spalten = ("id", "name", "schema", "claude_erlaubt", "nachtlauf", "nachtlauf_uhrzeit", "nachtlauf_zuletzt", "erstellt")
    zeilen = [dict(zip(spalten, z)) for z in roh.execute(
        f"SELECT {', '.join('m.' + s for s in spalten)} FROM {ZENTRAL}.mandanten m ORDER BY m.id").fetchall()]
    for z in zeilen:
        z["konten"] = [e for (e,) in roh.execute(
            f"SELECT k.email FROM {ZENTRAL}.konten k JOIN {ZENTRAL}.mitglieder mg ON mg.konto_id = k.id "
            "WHERE mg.mandant_id = %s ORDER BY k.id", (z["id"],)).fetchall()]
    return zeilen


def setze_claude(roh, mandant_id: int, erlaubt: bool) -> None:
    roh.execute(f"UPDATE {ZENTRAL}.mandanten SET claude_erlaubt = %s WHERE id = %s", (erlaubt, mandant_id))


def setze_nachtlauf(roh, mandant_id: int, an: bool, uhrzeit: str) -> None:
    if not (len(uhrzeit) == 5 and uhrzeit[2] == ":" and uhrzeit[:2].isdigit() and 0 <= int(uhrzeit[:2]) < 24):
        raise KontoFehler("Uhrzeit im Format HH:00.")
    roh.execute(f"UPDATE {ZENTRAL}.mandanten SET nachtlauf = %s, nachtlauf_uhrzeit = %s WHERE id = %s",
                (an, uhrzeit[:2] + ":00", mandant_id))


def nachtlauf(roh, mandant_id: int) -> tuple[bool, str, object]:
    z = roh.execute(f"SELECT nachtlauf, nachtlauf_uhrzeit, nachtlauf_zuletzt FROM {ZENTRAL}.mandanten WHERE id = %s",
                    (mandant_id,)).fetchone()
    return (bool(z[0]), z[1], z[2]) if z else (False, "01:00", None)


def faellige_nachtlaeufe(roh, jetzt: datetime) -> list[MandantInfo]:
    """Mandanten mit eingeschaltetem Nachtlauf, deren Uhrzeit heute erreicht ist und die heute noch nicht liefen."""
    return [MandantInfo(*z) for z in roh.execute(
        f"SELECT id, name, schema, rolle, claude_erlaubt FROM {ZENTRAL}.mandanten WHERE nachtlauf "
        "AND (nachtlauf_zuletzt IS NULL OR nachtlauf_zuletzt < %s::date) AND nachtlauf_uhrzeit <= %s ORDER BY id",
        (jetzt.date(), jetzt.strftime("%H:%M"))).fetchall()]


def nachtlauf_erledigt(roh, mandant_id: int, tag) -> None:
    roh.execute(f"UPDATE {ZENTRAL}.mandanten SET nachtlauf_zuletzt = %s WHERE id = %s", (tag, mandant_id))


def mandant_entfernen(roh, mandant_id: int) -> None:
    """Löscht Schema, Rolle und Zeile. Nur als Besitzer der Datenbank (Tests, Betreiber-CLI)."""
    z = roh.execute(f"SELECT schema, rolle FROM {ZENTRAL}.mandanten WHERE id = %s", (mandant_id,)).fetchone()
    if not z:
        return
    roh.execute(pgsql.SQL("SET ROLE {}").format(pgsql.Identifier(z[1])))
    try:
        roh.execute(pgsql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(pgsql.Identifier(z[0])))
    finally:
        roh.execute("RESET ROLE")
    roh.execute(f"DELETE FROM {ZENTRAL}.mandanten WHERE id = %s", (mandant_id,))
    roh.execute(pgsql.SQL("DROP ROLE IF EXISTS {}").format(pgsql.Identifier(z[1])))


def als_mandant(info: MandantInfo, ordner: Path) -> db.Mandant:
    return db.Mandant(info.id, info.name, info.schema, info.rolle, ordner, info.claude_erlaubt)


# --- Einladungen -----------------------------------------------------------------------------------------------------

def _code_hash(code: str) -> str:
    return hashlib.sha256(code.strip().encode()).hexdigest()


def einladung_erzeugen(roh, von_konto: int, notiz: str = "", mandant_id: int | None = None,
                       gueltig: timedelta = EINLADUNG_GUELTIG) -> str:
    """Der Code wird nur hier einmal zurückgegeben; gespeichert ist nur sein Hash."""
    code = secrets.token_urlsafe(18)
    roh.execute(f"INSERT INTO {ZENTRAL}.einladungen (code_hash, notiz, mandant_id, erstellt_von, gueltig_bis) "
                "VALUES (%s, %s, %s, %s, now() + %s)", (_code_hash(code), notiz.strip()[:200], mandant_id, von_konto, gueltig))
    protokolliere(roh, von_konto, "Einladung erzeugt", detail=notiz[:200])
    return code


def einladungen(roh) -> list[dict]:
    spalten = ("id", "notiz", "mandant_id", "erstellt", "gueltig_bis", "benutzt_am")
    return [dict(zip(spalten, z)) for z in roh.execute(
        f"SELECT {', '.join(spalten)} FROM {ZENTRAL}.einladungen ORDER BY id DESC LIMIT 100").fetchall()]


def einladung_zurueckziehen(roh, einladung_id: int) -> None:
    roh.execute(f"DELETE FROM {ZENTRAL}.einladungen WHERE id = %s AND benutzt_am IS NULL", (einladung_id,))


def registrieren(roh, code: str, email: str, passwort: str, name: str = "", ip: str = "") -> Konto:
    """Nur mit gültigem, unbenutztem Einladungscode. Ohne Mandant in der Einladung bekommt das Konto einen eigenen."""
    with roh.transaction():
        e = roh.execute(f"SELECT id, mandant_id FROM {ZENTRAL}.einladungen WHERE code_hash = %s AND benutzt_am IS NULL "
                        "AND gueltig_bis > now() FOR UPDATE", (_code_hash(code),)).fetchone()
        if not e:
            protokolliere(roh, None, "Registrierung abgelehnt", ip, "Code ungültig")
            raise KontoFehler("Der Einladungscode ist ungültig oder abgelaufen.")
        k = konto_anlegen(roh, email, passwort, name)
        if e[1] is not None:
            mitglied_machen(roh, k.id, e[1], "mitglied")
        else:
            mandant_anlegen(roh, name or k.email.split("@")[0], k.id)
        roh.execute(f"UPDATE {ZENTRAL}.einladungen SET benutzt_von = %s, benutzt_am = now() WHERE id = %s", (k.id, e[0]))
        protokolliere(roh, k.id, "Registriert mit Einladung", ip)
    return k


# --- Sitzungen (Web) -------------------------------------------------------------------------------------------------

def _token_hash(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def sitzung_anlegen(roh, konto_id: int, mandant_id: int, dauer: timedelta, ip: str = "") -> tuple[str, str]:
    token, csrf = secrets.token_urlsafe(32), secrets.token_urlsafe(24)
    roh.execute(f"INSERT INTO {ZENTRAL}.sitzungen (token_hash, konto_id, mandant_id, csrf, ablauf, ip) "
                "VALUES (%s, %s, %s, %s, now() + %s, %s)", (_token_hash(token), konto_id, mandant_id, csrf, dauer, ip[:64]))
    roh.execute(f"DELETE FROM {ZENTRAL}.sitzungen WHERE ablauf < now()")
    return token, csrf


def sitzung(roh, token: str, verlaengern: timedelta | None = None) -> dict | None:
    if not token or len(token) > 100:
        return None
    z = roh.execute(
        f"SELECT s.konto_id, s.mandant_id, s.csrf, k.email, k.name, k.admin FROM {ZENTRAL}.sitzungen s "
        f"JOIN {ZENTRAL}.konten k ON k.id = s.konto_id WHERE s.token_hash = %s AND s.ablauf > now() AND k.aktiv",
        (_token_hash(token),)).fetchone()
    if not z:
        return None
    if verlaengern:
        roh.execute(f"UPDATE {ZENTRAL}.sitzungen SET ablauf = now() + %s WHERE token_hash = %s", (verlaengern, _token_hash(token)))
    return {"konto": Konto(z[0], z[3], z[4], bool(z[5])), "mandant_id": z[1], "csrf": z[2]}


def sitzung_mandant(roh, token: str, mandant_id: int) -> None:
    roh.execute(f"UPDATE {ZENTRAL}.sitzungen SET mandant_id = %s WHERE token_hash = %s", (mandant_id, _token_hash(token)))


def sitzung_beenden(roh, token: str) -> None:
    roh.execute(f"DELETE FROM {ZENTRAL}.sitzungen WHERE token_hash = %s", (_token_hash(token),))


def andere_sitzungen_beenden(roh, konto_id: int, ausser_token: str = "") -> None:
    roh.execute(f"DELETE FROM {ZENTRAL}.sitzungen WHERE konto_id = %s AND token_hash <> %s",
                (konto_id, _token_hash(ausser_token) if ausser_token else ""))


# --- Übernahme eines bestehenden Schemas (Migration) -------------------------------------------------------------------

def schema_uebernehmen(roh, schema: str, name: str, inhaber_id: int, alte_rolle_erbt: bool = True) -> int:
    """Macht ein vorhandenes Schema (bisher „eine Person, ein Schema“) zu einem Mandanten, ohne Daten zu kopieren:
    neue Mandantenrolle, Besitz von Schema, Tabellen und Sequenzen geht an sie. `alte_rolle_erbt`: Der bisherige
    Besitzer (der Anmelde-Benutzer der Desktop-App) behält über die Mitgliedschaft Zugriff, damit eine laufende ältere
    App-Version weiterarbeitet."""
    if roh.execute(f"SELECT 1 FROM {ZENTRAL}.mandanten WHERE schema = %s", (schema,)).fetchone():
        raise KontoFehler(f"Das Schema {schema} gehört schon einem Mandanten.")
    if not roh.execute("SELECT 1 FROM information_schema.schemata WHERE schema_name = %s", (schema,)).fetchone():
        raise KontoFehler(f"Das Schema {schema} gibt es nicht.")
    ich = roh.execute("SELECT current_user").fetchone()[0]
    with roh.transaction():
        rolle = "js_m" + secrets.token_hex(7)
        roh.execute(pgsql.SQL("CREATE ROLE {} NOLOGIN").format(pgsql.Identifier(rolle)))
        roh.execute(pgsql.SQL("GRANT {} TO {} WITH INHERIT {}, SET TRUE").format(
            pgsql.Identifier(rolle), pgsql.Identifier(ich), pgsql.SQL("TRUE" if alte_rolle_erbt else "FALSE")))
        for (b,) in roh.execute(f"SELECT bt.rolle FROM {ZENTRAL}.betreiber bt JOIN pg_roles pr ON pr.rolname = bt.rolle "
                                "WHERE bt.rolle <> current_user").fetchall():
            roh.execute(pgsql.SQL("GRANT {} TO {} WITH INHERIT FALSE, SET TRUE").format(pgsql.Identifier(rolle), pgsql.Identifier(b)))
        roh.execute(pgsql.SQL("GRANT {} TO {}").format(pgsql.Identifier(GRUPPE), pgsql.Identifier(rolle)))
        s = pgsql.Identifier(schema)
        r = pgsql.Identifier(rolle)
        roh.execute(pgsql.SQL("ALTER SCHEMA {} OWNER TO {}").format(s, r))
        for (art, obj) in roh.execute(
                "SELECT CASE c.relkind WHEN 'S' THEN 'SEQUENCE' WHEN 'v' THEN 'VIEW' ELSE 'TABLE' END, c.relname "
                "FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                "WHERE n.nspname = %s AND c.relkind IN ('r', 'p', 'v') ORDER BY c.relname", (schema,)).fetchall():
            roh.execute(pgsql.SQL("ALTER {} {}.{} OWNER TO {}").format(pgsql.SQL(art), s, pgsql.Identifier(obj), r))
        # Identitäts-Sequenzen wandern mit ihrer Tabelle. Freie Sequenzen gibt es im Schema der App nicht.
        mid = roh.execute(f"INSERT INTO {ZENTRAL}.mandanten (name, schema, rolle) VALUES (%s, %s, %s) RETURNING id",
                          (name, schema, rolle)).fetchone()[0]
        mitglied_machen(roh, inhaber_id, mid, "inhaber")
        protokolliere(roh, inhaber_id, "Schema als Mandant übernommen", detail=schema)
    return mid
