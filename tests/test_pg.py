"""PostgreSQL-Schicht: Übersetzung immer, echte Server-Tests nur im Postgres-Lauf (JOBSUCHE_TEST_PG)."""

import sqlite3
import struct

import pytest

from jobsuche import config, db, pg, person, profil, rag

from conftest import _PG

nur_mit_server = pytest.mark.skipif(not _PG, reason="kein PostgreSQL-Testserver (JOBSUCHE_TEST_PG)")


def test_platzhalter_und_prozent_ausserhalb_und_innerhalb_von_literalen():
    sql = pg.uebersetze("SELECT * FROM firmen WHERE name LIKE '%?%' AND id = ? AND x = '50%'", True)
    assert sql == "SELECT * FROM firmen WHERE name ILIKE '%%?%%' AND id = %s AND x = '50%%'"


def test_ohne_parameter_bleibt_prozent_stehen():
    assert pg.uebersetze("SELECT '5%'", False) == "SELECT '5%'"


def test_benannte_parameter_aber_keine_typumwandlung():
    sql = pg.uebersetze("INSERT INTO t (a, b) VALUES (:a, :b::text)", True, benannt=True)
    assert sql == "INSERT INTO t (a, b) VALUES (%(a)s, %(b)s::text)"


def test_insert_or_ignore_wird_on_conflict():
    sql = pg.uebersetze("INSERT OR IGNORE INTO nacht_gesehen (schluessel, datum) VALUES (?, ?)", True)
    assert sql == "INSERT INTO nacht_gesehen (schluessel, datum) VALUES (%s, %s) ON CONFLICT DO NOTHING"


def test_vektorabstand_und_group_concat():
    sql = pg.uebersetze("SELECT min(vec_distance_cosine(a.embedding, ?)), group_concat(t, ' ') FROM c", True)
    assert sql == "SELECT min((a.embedding <=> %s)), string_agg(t, ' ') FROM c"


def test_schema_typen_und_fts_entfallen():
    aus = pg.ddl(db.SCHEMA)
    assert "fts5" not in aus and "TRIGGER" not in aus
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in aus
    assert "embedding vector NOT NULL" in aus
    assert "id BIGINT PRIMARY KEY CHECK (id = 1)" in aus  # person bleibt Einzelzeile mit fester ID
    assert "DOUBLE PRECISION" in pg.ddl("CREATE TABLE w (kalt REAL)")


def test_vektor_hin_und_zurueck():
    blob = struct.pack("3f", 0.5, -1.25, 2.0)
    text = pg.vektor_text(blob)
    assert text == "[0.5,-1.25,2.0]"
    assert pg._VektorLoader(0).load(text.encode()) == blob


def test_schema_folgt_dem_pfad(tmp_path):
    a = pg.schema_fuer(tmp_path / "jobsuche.db", tmp_path)
    b = pg.schema_fuer(tmp_path / "personen" / "x" / "jobsuche.db", tmp_path)
    assert a != b and a.startswith("js_") and len(a) == 19
    assert a == pg.schema_fuer(tmp_path / "jobsuche.db", tmp_path)


def test_ohne_einstellung_bleibt_es_sqlite(tmp_path, monkeypatch):
    monkeypatch.setattr(db, "_server", None)
    conn = db.verbinden(tmp_path / "x.db")
    assert isinstance(conn, sqlite3.Connection) and not db.ist_postgres(conn)
    conn.close()


def test_einstellung_ohne_passwort_in_der_datei(tmp_path, monkeypatch):
    monkeypatch.setattr(config, "DATEN", tmp_path)
    monkeypatch.setattr(db, "_server", db._UNGELADEN)
    db.speichere_server({"host": "db.example", "port": 5432, "datenbank": "jobsuche", "benutzer": "u",
                         "passwort": "geheim", "sslmode": "require"})
    inhalt = (tmp_path / "datenbank.json").read_text()
    assert "geheim" not in inhalt and "db.example" in inhalt
    monkeypatch.setattr(db, "_server", db._UNGELADEN)
    assert db.server()["host"] == "db.example"
    db.speichere_server(None)
    monkeypatch.setattr(db, "_server", db._UNGELADEN)
    assert db.server() is None


@nur_mit_server
def test_uebernahme_kopiert_alles_und_laesst_die_datei_stehen(tmp_path, monkeypatch):
    monkeypatch.setattr(db, "_server", None)
    quelle = tmp_path / "alt.db"
    alt = db.verbinden(quelle)
    person.speichere(alt, name="Test Person", email="test@example.org")
    fakt = profil.lege_fakt_an(alt, "technik", "Python und PostgreSQL im Betrieb", "Test")
    profil.bestaetige(alt, fakt)
    alt.execute("INSERT INTO firmen (name, sitz) VALUES ('Muster GmbH', 'Bremen')")
    alt.commit()
    vorher = {t: alt.execute(f"SELECT count(*) FROM {t}").fetchone()[0] for t in ("person", "fakten", "chunks", "firmen")}
    alt.close()
    groesse = quelle.stat().st_size

    monkeypatch.setattr(db, "_server", _PG)
    ziel = db.verbinden(tmp_path / "neu.db")
    try:
        ergebnis = pg.uebernimm(quelle, ziel)
        for t, n in vorher.items():
            assert ergebnis[t][:2] == (n, n)
        # Die Suche findet den Fakt auf dem Server über Vektor und Volltext
        treffer = rag.fakten(ziel, "PostgreSQL Betrieb")
        assert treffer and "PostgreSQL" in treffer[0]["text"]
        # Neue IDs setzen hinter den übernommenen fort
        neu = profil.lege_fakt_an(ziel, "technik", "Ein zweiter Fakt", "Test")
        assert neu > fakt
        with pytest.raises(ValueError):
            pg.uebernimm(quelle, ziel)  # ohne „ersetzen“ nie über vorhandene Daten
    finally:
        ziel.close()
    assert quelle.stat().st_size == groesse


@nur_mit_server
def test_fehler_kommen_als_sqlite_ausnahmen(conn):
    with pytest.raises(sqlite3.IntegrityError):
        conn.execute("INSERT INTO person (id, name, email) VALUES (1, 'Doppelt', 'x@example.org')")
    # Ein Fehler bricht keine Folgeabfragen ab (Autocommit wie bei SQLite)
    assert conn.execute("SELECT name FROM person WHERE id = 1").fetchone()["name"] == "Test Person"
